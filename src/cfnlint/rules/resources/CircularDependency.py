from copy import copy

from cfnlint._typing import RuleMatches
from cfnlint.graph import Graph
from cfnlint.rules import CloudFormationLintRule, RuleMatch
from cfnlint.schema import PROVIDER_SCHEMA_MANAGER, ResourceNotFoundError
from cfnlint.template import Template


class CircularDependency(CloudFormationLintRule):
    """Check if Resources have a circular dependency"""

    id = "E3004"
    shortdesc = "Resource dependencies are not circular"
    description = (
        "Check that Resources are not circularly dependent by DependsOn, Ref, Sub, or"
        " GetAtt"
    )
    source_url = "https://github.com/aws-cloudformation/cfn-lint"
    tags = ["resources", "circularly", "dependson", "ref", "sub", "getatt"]

    # Only dependencies of the underlying resource (or its execution role)
    # belong on the SAM logical ID. Stage, event and deployment-preference
    # properties belong to separate resources generated by the transform.
    _sam_resources = {
        "AWS::Serverless::Function": (
            "AWS::Lambda::Function",
            {
                "CodeUri",
                "ImageUri",
                "Policies",
                "AssumeRolePolicyDocument",
                "PermissionsBoundary",
                "RolePath",
                "Tracing",
            },
        ),
        "AWS::Serverless::Api": (
            "AWS::ApiGateway::RestApi",
            {"DefinitionBody", "DefinitionUri"},
        ),
        "AWS::Serverless::HttpApi": (
            "AWS::ApiGatewayV2::Api",
            {"DefinitionBody", "DefinitionUri"},
        ),
        "AWS::Serverless::WebSocketApi": (
            "AWS::ApiGatewayV2::Api",
            {"DefinitionBody", "DefinitionUri"},
        ),
        "AWS::Serverless::Application": ("AWS::CloudFormation::Stack", {"Location"}),
        "AWS::Serverless::SimpleTable": ("AWS::DynamoDB::Table", {"PrimaryKey"}),
        "AWS::Serverless::LayerVersion": ("AWS::Lambda::LayerVersion", {"ContentUri"}),
        "AWS::Serverless::StateMachine": (
            "AWS::StepFunctions::StateMachine",
            {
                "DefinitionBody",
                "DefinitionUri",
                "Role",
                "Logging",
                "Tracing",
                "Policies",
                "PermissionsBoundary",
            },
        ),
    }

    def _dependency_graph(self, cfn: Template, original_graph: Graph) -> Graph:
        if not any(
            resource.get("Type", "").startswith("AWS::Serverless::")
            for resource in cfn.get_resources().values()
            if isinstance(resource.get("Type"), str)
        ):
            return original_graph
        graph = copy(original_graph)
        graph.graph = original_graph.graph.copy()
        property_cache: dict[str, set[str]] = {}
        for source, target, key, data in list(graph.graph.edges(keys=True, data=True)):
            resource_type = graph.graph.nodes[source].get("resource_type", "")
            if not resource_type.startswith("AWS::Serverless::"):
                continue
            path = data.get("source_paths", [])
            if path == ["DependsOn"]:
                continue
            if resource_type not in property_cache:
                properties: set[str] = set()
                if resource_type in self._sam_resources:
                    cfn_type, extra_properties = self._sam_resources[resource_type]
                    try:
                        schema = PROVIDER_SCHEMA_MANAGER.get_resource_schema(
                            cfn.regions[0], cfn_type
                        ).schema
                        properties.update(schema.get("properties", {}))
                        properties.update(extra_properties)
                    except ResourceNotFoundError:
                        pass
                property_cache[resource_type] = properties
            role_is_explicit = (
                resource_type
                in {"AWS::Serverless::Function", "AWS::Serverless::StateMachine"}
                and "Role" in cfn.get_resources()[source].get("Properties", {})
                and len(path) > 1
                and path[1]
                in {
                    "Policies",
                    "AssumeRolePolicyDocument",
                    "PermissionsBoundary",
                    "RolePath",
                }
            )
            if (
                role_is_explicit
                or len(path) < 2
                or path[0] != "Properties"
                or path[1] not in property_cache[resource_type]
            ):
                graph.graph.remove_edge(source, target, key)
        return graph

    def match(self, cfn: Template) -> RuleMatches:
        matches = []

        if cfn.graph is None:
            return []
        graph = self._dependency_graph(cfn, cfn.graph)
        for cycle in graph.get_cycles(cfn):
            source, target = cycle[:2]
            if (
                cfn.graph.graph.nodes[source].get("type") == "Resource"
                and cfn.graph.graph.nodes[target].get("type") == "Resource"
            ):
                message = (
                    f"Circular Dependencies for resource {source}. Circular dependency"
                    f" with [{target}]"
                )
                path = ["Resources", source]
                matches.append(RuleMatch(path, message))

        return matches
